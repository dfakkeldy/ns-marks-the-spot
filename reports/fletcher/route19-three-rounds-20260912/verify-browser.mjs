await page.waitForFunction(()=>{const c=document.querySelector('.leaflet-user-maps-pane-pane canvas');if(!c)return false;return c.width>0&&c.getContext('2d').getImageData(0,0,c.width,c.height).data.some((v,i)=>i%4===3&&v>0)});
const after=await storedProof();if(before.storedRasterSha256!==after.storedRasterSha256)throw new Error('Raster hash changed on reload');
await fs.writeFile(out+'/verification.json',JSON.stringify({tooling:'Playwright; Browser plugin not available',before,after,enabledStateSurvived:true},null,2));
await page.screenshot({path:out+'/reload-desktop.png'});
