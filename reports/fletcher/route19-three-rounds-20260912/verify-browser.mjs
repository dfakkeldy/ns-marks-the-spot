await page.waitForFunction(()=>{const c=document.querySelector('.leaflet-user-maps-pane-pane canvas');if(!c)return false;return c.width>0&&c.getContext('2d').getImageData(0,0,c.width,c.height).data.some((v,i)=>i%4===3&&v>0)}, {timeout:60000});
async function storedProof(){return await page.evaluate(async()=>{
 const {UserMapStore}=await import('/src/userMaps/store/userMapStore.ts');
 const store=await UserMapStore.open();const records=await store.listUserMaps();const record=records[0];const blob=await store.getRasterBlob(record.id);
 const hash=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',await blob.arrayBuffer()))).map(n=>n.toString(16).padStart(2,'0')).join('');
 const preview=await store.getPreviewBlob(record.id);const bitmap=await createImageBitmap(preview);const previewSize=[bitmap.width,bitmap.height];const canvas=new OffscreenCanvas(bitmap.width,bitmap.height);const ctx=canvas.getContext('2d');ctx.drawImage(bitmap,0,0);const data=ctx.getImageData(0,0,bitmap.width,bitmap.height).data;let transparent=0,opaque=0;for(let i=3;i<data.length;i+=4){if(data[i]===0)transparent++;if(data[i]===255)opaque++}bitmap.close();store.close();
 return {record,previewSize,storedRasterSha256:hash,rasterBytes:blob.size,rasterMime:blob.type,transparentPixels:transparent,opaquePixels:opaque};
})}
const before=await storedProof(); if(before.storedRasterSha256 !== (await import('node:crypto')).createHash('sha256').update(await fs.readFile(raster)).digest('hex')) throw new Error('Wrong raster hash');
await fs.writeFile(out+'/import.txt',await page.locator('body').innerText());
