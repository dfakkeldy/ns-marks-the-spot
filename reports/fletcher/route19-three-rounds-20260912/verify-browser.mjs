import { chromium } from '../../../web/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
const [raster, out, position] = process.argv.slice(2);
if (!raster || !out) throw new Error('Usage: node verify-browser.mjs RASTER OUTPUT_DIRECTORY');
